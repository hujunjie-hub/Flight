"""S06-085: measure the curve that M5-06 proves versus the curve M6 consumes.

spec/02 requires M5-06 to validate "the piecewise curve that is actually
published and consumed". The consumer (control_sample_reference() in
middleware/model/control/outer_loop/quad_x4/position_tracking/control_reference.c)
evaluates the quintic Hermite in binary32 with Horner's rule, while the M5-06
validator rebuilds the same algebraic curve in binary64 and only adds the
binary32 conversion error of the midpoint to its position interval.

This verifier quantifies the difference between the two evaluations for a fixed
seed. It does not replace a proof: the measured gap is reported so that the
independent mathematical review (MR-009) can decide whether the validator must
replicate the consumer arithmetic or add an explicit evaluation-error term.

Regimes:
  smooth      endpoint states generated by integrating a bounded jerk over one
              20 ms interval, i.e. the data shape a real reference contains;
  adversarial independent random p/v/a endpoints, which maximises coefficient
              cancellation in the binary32 Horner evaluation.

Exit code 0 requires both regimes to stay below their documented ceilings. The
ceilings are regression bounds on the measured gap, not a safety proof.
"""
import math
import random
import struct
import sys

SEED = 0x6D350685
H = struct.unpack('f', struct.pack('f', 20000 * struct.unpack('f', struct.pack('f', 1e-6))[0]))[0]
SAMPLES = 33
SEGMENTS = 256
SMOOTH_CEILING_M = 1.0e-4
ADVERSARIAL_CEILING_M = 5.0e-3


def f32(x):
    return struct.unpack('f', struct.pack('f', x))[0]


def consumer_binary32(p0, v0, a0, p1, v1, a1, h, s):
    """Binary32 Horner evaluation, mirroring control_reference.c line by line."""
    p0, v0, a0 = f32(p0), f32(v0), f32(a0)
    p1, v1, a1 = f32(p1), f32(v1), f32(a1)
    h, s = f32(h), f32(s)
    d = f32(f32(f32(p1 - p0) - f32(h * v0)) - f32(f32(f32(0.5 * h) * h) * a0))
    dv = f32(f32(v1 - v0) - f32(h * a0))
    da = f32(a1 - a0)
    hh = f32(h * h)
    c3 = f32(f32(f32(f32(10.0 * d) / f32(hh * h)) - f32(f32(4.0 * dv) / hh))
             + f32(da / f32(2.0 * h)))
    c4 = f32(f32(f32(f32(-15.0 * d) / f32(hh * hh)) + f32(f32(7.0 * dv) / f32(hh * h)))
             - f32(da / hh))
    c5 = f32(f32(f32(f32(6.0 * d) / f32(hh * hh * h)) - f32(f32(3.0 * dv) / f32(hh * hh)))
             + f32(da / f32(2.0 * f32(hh * h))))
    c2 = f32(0.5 * a0)
    return f32(f32(f32(f32(f32(c5 * s + c4) * s + c3) * s + c2) * s + v0) * s + p0)


def exact_binary64(p0, v0, a0, p1, v1, a1, h, s):
    d = (p1 - p0) - h * v0 - 0.5 * h * h * a0
    dv = (v1 - v0) - h * a0
    da = a1 - a0
    c3 = 10.0 * d / h ** 3 - 4.0 * dv / h ** 2 + da / (2.0 * h)
    c4 = -15.0 * d / h ** 4 + 7.0 * dv / h ** 3 - da / h ** 2
    c5 = 6.0 * d / h ** 5 - 3.0 * dv / h ** 4 + da / (2.0 * h ** 3)
    c2 = 0.5 * a0
    return ((((c5 * s + c4) * s + c3) * s + c2) * s + v0) * s + p0


def smooth_segment(rnd):
    """Endpoints produced by constant jerk over one preview interval."""
    scale = rnd.choice([1.0, 10.0, 100.0, 500.0])
    p0 = [rnd.uniform(-scale, scale) for _ in range(3)]
    v0 = [rnd.uniform(-10.0, 10.0) for _ in range(3)]
    a0 = [rnd.uniform(-5.0, 5.0) for _ in range(3)]
    jerk = [rnd.uniform(-20.0, 20.0) for _ in range(3)]
    h = H
    p1 = [p0[i] + v0[i] * h + 0.5 * a0[i] * h * h + jerk[i] * h ** 3 / 6.0
          for i in range(3)]
    v1 = [v0[i] + a0[i] * h + 0.5 * jerk[i] * h * h for i in range(3)]
    a1 = [a0[i] + jerk[i] * h for i in range(3)]
    return p0, v0, a0, p1, v1, a1


def adversarial_segment(rnd):
    scale = rnd.choice([1.0, 10.0, 100.0, 500.0])
    p0 = [rnd.uniform(-scale, scale) for _ in range(3)]
    p1 = [rnd.uniform(-scale, scale) for _ in range(3)]
    v0 = [rnd.uniform(-40.0, 40.0) for _ in range(3)]
    v1 = [rnd.uniform(-40.0, 40.0) for _ in range(3)]
    a0 = [rnd.uniform(-20.0, 20.0) for _ in range(3)]
    a1 = [rnd.uniform(-20.0, 20.0) for _ in range(3)]
    return p0, v0, a0, p1, v1, a1


def measure(generator, rnd, segments):
    worst = 0.0
    worst_sample = 0
    for _ in range(segments):
        segment = generator(rnd)
        for k in range(SAMPLES):
            s = H * k / (SAMPLES - 1)
            for axis in range(3):
                p0, v0, a0, p1, v1, a1 = (values[axis] for values in segment)
                gap = abs(consumer_binary32(p0, v0, a0, p1, v1, a1, H, s)
                          - exact_binary64(p0, v0, a0, p1, v1, a1, H, s))
                if gap > worst:
                    worst = gap
                    worst_sample = k
    return worst, worst_sample


def main():
    smooth_rnd = random.Random(SEED)
    adversarial_rnd = random.Random(SEED ^ 0x5A5A5A5A)
    smooth, smooth_sample = measure(smooth_segment, smooth_rnd, SEGMENTS)
    adversarial, adversarial_sample = measure(adversarial_segment, adversarial_rnd, SEGMENTS)
    print(f"M5_S06_085_CURVE_EVAL_GAP_REPORT seed=0x{SEED:X} segments={SEGMENTS} "
          f"samples={SAMPLES} smooth_max_m={smooth:.6e} "
          f"smooth_worst_sample={smooth_sample} "
          f"adversarial_max_m={adversarial:.6e} "
          f"adversarial_worst_sample={adversarial_sample}")
    failures = []
    if not math.isfinite(smooth) or smooth > SMOOTH_CEILING_M:
        failures.append(f"smooth curve gap {smooth:.3e} m > {SMOOTH_CEILING_M:.1e} m")
    if not math.isfinite(adversarial) or adversarial > ADVERSARIAL_CEILING_M:
        failures.append(
            f"adversarial curve gap {adversarial:.3e} m > {ADVERSARIAL_CEILING_M:.1e} m")
    if failures:
        for failure in failures:
            print(f"FAIL: {failure}")
        return 1
    print("M5_S06_085_CURVE_EVAL_GAP_WITHIN_CEILING "
          "(gap is NOT yet covered by the validator interval; see MR-009)")
    return 0


if __name__ == '__main__':
    sys.exit(main())
