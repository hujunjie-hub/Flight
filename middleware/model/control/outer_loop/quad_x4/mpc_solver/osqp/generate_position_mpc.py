"""Reproduce the OSQP 1.0.0 float, matrix-parameter embedded workspace.
Run with a Host-only environment containing osqp==1.0.0, numpy and scipy.
"""
from pathlib import Path
import hashlib
import json
import re
import numpy as np
import scipy.sparse as sp
import osqp

assert osqp.__version__ == '1.0.0', osqp.__version__
out = Path(__file__).resolve().parent / 'generated'
# Condensed MPC has no cross-axis Hessian terms. Retain all per-axis upper
# entries, including values that happen to be zero in the seed problem.
P = sp.csc_matrix((15, 15))
pr, pc = [], []
for c in range(15):
    for r in range(c + 1):
        if r % 3 == c % 3:
            pr.append(r); pc.append(c)
P = sp.csc_matrix((np.array([2.0 if r == c else .001 for r, c in zip(pr, pc)]),
                   (pr, pc)), shape=(15, 15))
rows, cols, vals = [], [], []
for col in range(15):
    axis, move = col % 3, col // 3
    for step in range(1, 21):
        if step > move:
            for state in (axis, axis + 3):
                rows.append((step - 1) * 6 + state); cols.append(col); vals.append(.01)
    rows.append(120 + col); cols.append(col); vals.append(1.)
    rows.append(135 + col); cols.append(col); vals.append(1.)
    if move < 4:
        rows.append(135 + col + 3); cols.append(col); vals.append(-1.)
    for side in range(8):
        rows.append(150 + move * 8 + side); cols.append(col); vals.append(.1)
A = sp.csc_matrix((vals, (rows, cols)), shape=(190, 15))
m = osqp.OSQP()
m.setup(P=P, q=np.zeros(15), A=A, l=-np.ones(190)*100,
        u=np.ones(190)*100, max_iter=80, eps_abs=1e-3, eps_rel=1e-3,
        polishing=False, adaptive_rho=True, adaptive_rho_interval=25,
        check_termination=1, verbose=False, scaled_termination=False,
        scaling=0, rho_is_vec=False)
m.codegen(str(out), parameters='matrices', use_float=True,
          prefix='quad_', force_rewrite=True, include_codegen_src=True)
# Embedded matrix updates never change the fixed symbolic sparsity. Preserve
# that immutable data in Flash. The upstream ABI uses mutable index pointers;
# casts here initialize those pointers, but no firmware path writes the arrays.
workspace = out / 'quad_workspace.c'
code = workspace.read_text()
code = code.replace('OSQPFloat quad_sol_prim_inf_cert[190];', 'extern OSQPFloat quad_work_delta_y_val[190];')
code = code.replace('OSQPFloat quad_sol_dual_inf_cert[15];', 'extern OSQPFloat quad_work_delta_x_val[15];')
code = code.replace('  quad_sol_prim_inf_cert,', '  quad_work_delta_y_val,')
code = code.replace('  quad_sol_dual_inf_cert,', '  quad_work_delta_x_val,')
immutable = re.findall(r'^OSQPInt (quad_(?:data_.*_csc_[pi]|linsys_(?:L_[pi]|P|KKT_[pi]|PtoKKT|AtoKKT|rhotoKKT|etree|Lnz)))\[', code, re.M)
for name in immutable:
    code = code.replace('OSQPInt '+name+'[', 'const OSQPInt '+name+'[')
    code = re.sub(r'(?m)^(\s*)'+name+r',', r'\1(OSQPInt *)'+name+',', code)
workspace.write_text(code)
# QDLDL's numeric refactorization rewrites the same L symbolic indices. With
# a fixed generated graph, verify those indices instead of writing to Flash;
# a pattern mismatch is a hard numerical failure, never silent corruption.
qdldl = out / 'src/qdldl.c'
code = qdldl.read_text()
for before, after in [
    ('Lp[0] = 0;', 'if (Lp[0] != 0) return -1;'),
    ('Lp[i + 1] = Lp[i] + Lnz[i];', 'if (Lp[i + 1] != Lp[i] + Lnz[i]) return -1;'),
    ('Li[tmpIdx] = k;', 'if (Li[tmpIdx] != k) return -1;')]:
    assert code.count(before) == 1, before
    code = code.replace(before, after)
qdldl.write_text(code)
pattern = out.parent / 'mpc_sparsity_pattern.h'
with pattern.open('w', encoding='utf-8') as f:
    f.write('/* Generated by middleware/model/control/outer_loop/quad_x4/mpc_solver/osqp/generate_position_mpc.py; fixed CSC pattern. */\n')
    for name, mat in [('p', P), ('a', A)]:
        for suffix, data in [('ptr', mat.indptr), ('row', mat.indices)]:
            f.write('static const int qp_%s_%s[%d]={%s};\n' %
                    (name, suffix, len(data), ','.join(map(str, data))))
lock = {'version': '1.0.0', 'generator': 'osqp Python 1.0.0',
        'mode': 2, 'float': True, 'variables': 15, 'constraints': 190,
        'p_nnz': P.nnz, 'a_nnz': A.nnz, 'max_iter': 80,
        'adaptive_rho_interval': 25, 'license': 'Apache-2.0',
        'scaling': 0, 'rho_is_vec': False,
        'local_modifications': 'Symbolic index arrays const in Flash; static pointer casts; QDLDL numeric refactor verifies fixed L indices; embedded unused certificate buffers alias their delta work vectors.',
        'source': 'https://github.com/osqp/osqp/tree/v1.0.0',
        'files': {p.relative_to(out).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                  for p in sorted(out.rglob('*')) if p.is_file()
                  and p.suffix not in {'.o', '.su'}}}
(out.parent / 'UPSTREAM_LOCK.json').write_text(json.dumps(lock, indent=2)+'\n')
print('Generated:', P.nnz, 'P entries,', A.nnz, 'A entries')
