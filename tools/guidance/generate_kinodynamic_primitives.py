#!/usr/bin/env python3
"""Generate the fixed M5 Kinodynamic A* primitive table from its YAML manifest.

The manifest is JSON-compatible YAML so this generator needs only Python stdlib.
Run with --check in CI to reject stale generated C.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "config" / "kinodynamic_primitives.yaml"
OUTPUT = ROOT / "middleware" / "guidance" / "trajectory_planning" / "kinodynamic_primitives_generated.h"

KINDS = {
    "TRANSLATE": "M5_PRIMITIVE_TRANSLATE",
    "CARDINAL_FAST": "M5_PRIMITIVE_TRANSLATE",
    "VERTICAL": "M5_PRIMITIVE_VERTICAL",
    "YAW": "M5_PRIMITIVE_YAW",
    "WAIT": "M5_PRIMITIVE_WAIT",
    "BRAKE": "M5_PRIMITIVE_BRAKE",
}


def c_float(value: float) -> str:
    text = format(float(value), ".10g")
    if "." not in text and "e" not in text.lower():
        text += ".0"
    return text + "f"


def build_rows(spec: dict) -> list[tuple[str, int, int, int, float, float, int]]:
    rows = []
    for group in spec["groups"]:
        kind = group["kind"]
        if kind not in KINDS:
            raise ValueError(f"unsupported primitive group: {kind}")
        durations = group["duration_us"]
        if kind in ("TRANSLATE", "CARDINAL_FAST", "VERTICAL"):
            speeds = group["speeds_mps"]
            for direction in group["dirs"]:
                for speed_id, speed in enumerate(speeds):
                    for duration_id, duration in enumerate(durations):
                        rows.append((KINDS[kind], int(direction), speed_id, duration_id,
                                     float(speed), 0.0, int(duration)))
        elif kind == "YAW":
            for direction in group["dirs"]:
                for step in group["yaw_bin_steps"]:
                    for duration_index, duration in enumerate(durations):
                        yaw_rate = (int(direction["sign"]) * int(step) *
                                    (2.0 * math.pi / spec["velocity_bins"]["yaw_bins"]) /
                                    (int(duration) * 1e-6))
                        rows.append((KINDS[kind], int(direction["dir"]), int(step),
                                     2 + duration_index, 0.0, yaw_rate, int(duration)))
        else:
            for direction in group["dirs"]:
                for duration_index, duration in enumerate(durations):
                    rows.append((KINDS[kind], int(direction), 0, duration_index,
                                 0.0, 0.0, int(duration)))
    if len(rows) != int(spec["entry_count"]):
        raise ValueError(f"manifest declares {spec['entry_count']} entries but generates {len(rows)}")
    if int(spec["capacity"]) != 64 or int(spec["entry_size_bytes"]) != 16:
        raise ValueError("V1.9.1 primitive capacity/record size changed")
    if int(spec["reserved_entries_zero_filled"]) != 4:
        raise ValueError("V1.9.1 requires four zero-filled reserved entries")
    return rows


def render(spec: dict) -> str:
    rows = build_rows(spec)
    lines = [
        "/* Generated by tools/guidance/generate_kinodynamic_primitives.py; do not edit. */",
        "#ifndef KINODYNAMIC_PRIMITIVES_GENERATED_H",
        "#define KINODYNAMIC_PRIMITIVES_GENERATED_H",
        "",
        f"#define M5_KINODYNAMIC_PRIMITIVE_COUNT {len(rows)}u",
        f"#define M5_KINODYNAMIC_PRIMITIVE_CAPACITY {int(spec['capacity'])}u",
        "",
        "static const M5KinodynamicPrimitive m5_kinodynamic_primitives[M5_KINODYNAMIC_PRIMITIVE_CAPACITY] = {",
    ]
    for kind, direction, speed_id, duration_id, speed, yaw_rate, duration in rows:
        lines.append(
            f"  {{{kind}, {direction}u, {speed_id}u, {duration_id}u, "
            f"{c_float(speed)}, {c_float(yaw_rate)}, {duration}u}},"
        )
    for _ in range(int(spec["reserved_entries_zero_filled"])):
        lines.append("  {0u, 0u, 0u, 0u, 0.0f, 0.0f, 0u},")
    lines.extend(["};", "", "#endif /* KINODYNAMIC_PRIMITIVES_GENERATED_H */", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    spec = json.loads(MANIFEST.read_text(encoding="utf-8"))
    generated = render(spec)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("generated Kinodynamic primitive table is stale; run generator")
        print("KINODYNAMIC_PRIMITIVES_GENERATED_OK")
        return 0
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
