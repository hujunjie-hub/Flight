"""Generate FCU offsets/CRC from the authoritative dialect using mavgen.

uv run --no-project --with pymavlink==2.4.49 python tools/generate_fcu_mavlink_layout.py
"""
from importlib.metadata import version
import hashlib
import json
from pathlib import Path
from pymavlink.generator import mavparse

ROOT = next(p for p in Path(__file__).resolve().parents if (p/'SConstruct').is_file())
if version('pymavlink') != '2.4.49':
    raise SystemExit('Install pymavlink==2.4.49 to regenerate the FCU layout.')
source=ROOT/'spec/contracts/FCU.xml'
x=mavparse.MAVXML(str(source),wire_protocol_version='2.0')
lines=['/* Generated by pymavlink 2.4.49; do not edit. */','#ifndef WIRE_LAYOUT_H',
       '#define WIRE_LAYOUT_H']
for m in x.message:
    prefix=m.name
    lines += [f'#define {prefix}_ID {m.id}u',f'#define {prefix}_LEN {m.wire_length}u',
              f'#define {prefix}_CRC {m.crc_extra}u']
    for f in m.ordered_fields:
        lines.append(f'#define {prefix}_{f.name.upper()} {f.wire_offset}u')
lines+=['#endif','']
out=ROOT/'middleware/protocol/mavlink/fcu_mavlink_layout.h'
out.write_text('\n'.join(lines),encoding='utf-8',newline='\n')
(out.parent/'wire_generation.json').write_text(json.dumps({
    'generator':'pymavlink==2.4.49','input':source.relative_to(ROOT).as_posix(),
    'input_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
    'output_sha256':hashlib.sha256(out.read_bytes()).hexdigest(),
    'messages':[{ 'id':m.id,'name':m.name,'length':m.wire_length,'crc_extra':m.crc_extra}
                for m in x.message]},indent=2)+'\n',encoding='utf-8',newline='\n')
print('Generated',len(x.message),'FCU message layouts')
